const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..');
const context = {window: {}, document: {}, TR: {}, console, setTimeout, clearTimeout, requestAnimationFrame: callback => callback()};
context.window = context;
context.window.TR = context.TR;
vm.createContext(context);
for (const name of ['config.js','utils.js','ref-templates.js','knowledge.js','data-adapters.js','data-model.js','reuse-lab.js']) {
  vm.runInContext(fs.readFileSync(path.join(root,name),'utf8'),context,{filename:name});
}
const {TR} = context;
const raw = JSON.parse(fs.readFileSync(path.join(__dirname,'fixtures/V5_SYNTHETIC_TEST_ONLY.json'),'utf8'));
(async () => {
  const parsed = TR.dataAdapters.parseSourceText(JSON.stringify(raw),'v5-test.json');
  assert.equal(parsed.kind,'textreuse');
  const dm = await TR.DataModel.fromRaw(parsed.raw,'v5-test.json',()=>{},{datasetId:'v5-demo'});
  assert.equal(dm.records.length,2);
  assert.equal(dm.candidateCount,4, 'self matches must be excluded');
  const first=dm.records.find(r=>r.rawId==='Demo_Source_p_1_1');
  const c1=first.candidates.find(c=>c.rawCandidateId==='candidate-1');
  const c2=first.candidates.find(c=>c.rawCandidateId==='candidate-2');
  const noPairs=first.candidates.find(c=>c.rawCandidateId==='candidate-3');
  const second=dm.records.find(r=>r.rawId==='Demo_Source_p_1_2');
  const c4=second.candidates.find(c=>c.rawCandidateId==='candidate-4');
  assert.ok(c1&&c2&&c4&&noPairs, 'synthetic corpus record parsing');
  const s1=TR.reuseLab.statistics(first,c1),s2=TR.reuseLab.statistics(first,c2),s4=TR.reuseLab.statistics(second,c4);
  assert.equal(s1.matched,5);
  assert.equal(s1.sumWords,5);
  assert.equal(s1.longestRun,2);
  assert.equal(s1.exactPct,0.8);
  assert.equal(s1.coverage,5/8);
  assert.equal(s2.longestRun,1,'gapped indices should not form a parallel run');
  assert.equal(s4.longestRun,3);
  assert.equal(TR.reuseLab.statistics(first,noPairs).known,false);
  assert.equal(TR.reuseLab.metricValue(first,noPairs,'matched'),null,'missing is not zero');
  assert.equal(TR.reuseLab.metricValue(first,c1,'score'),48.5);
  const marked=TR.reuseLab.renderWords(first,c1,'original');
  assert.ok(marked.includes('data-tr-ids="0"'));
  assert.ok(marked.includes('data-tr-ids="1"'));
  assert.ok(marked.includes('v5-morph'));
  assert.ok(marked.includes('background-color:'));
  const contextOnly=TR.reuseLab.renderWords(first,c1,'original',{contextOnly:true,context:0});
  assert.ok(contextOnly.includes('v5-ellipsis'),'context mode should collapse unaligned text');
  const csv=TR.reuseLab.rowsCsv([{record:first,candidate:c1}]);
  assert.ok(csv.includes('longest_run'));
  assert.ok(csv.includes('48.5'));
  assert.ok(csv.includes('"Demo_Parallel_A_p_2_1"'));
  const word=TR.reuseLab.docPage([{record:first,candidate:c1}]);
  assert.ok(word.includes('<!doctype html>'));
  assert.ok(word.includes('background-color:'));
  assert.ok(word.includes('data-tr-ids'));
  const idx=fs.readFileSync(path.join(root,'index.html'),'utf8');
  const app=fs.readFileSync(path.join(root,'app.js'),'utf8');
  assert.ok(idx.includes('data-view="explore"'));
  assert.ok(idx.includes('data-color-mode="groups"'));
  assert.ok(idx.includes('src="reuse-lab.js"'));
  assert.ok(idx.includes('src="pptxgen.min.js"'));
  assert.ok(app.includes("state.activeView === 'explore'"));
  assert.ok(app.includes('openParallelFromLab('));
  assert.ok(app.includes("state.colorMode === 'groups'"));
  assert.ok(fs.statSync(path.join(root,'pptxgen.min.js')).size>100000);
  console.log('V5 parallel explorer model, metrics, alignment, exports and wiring tests passed');
})().catch(err=>{console.error(err);process.exitCode=1;});
